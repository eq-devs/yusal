String _d(String number) => number.replaceAll('.', ',');

/// Default room and floor names inside core messages, in Kazakh or
/// Russian.
String _name(String zh) {
  const rooms = {
    '客厅': ('Қонақ бөлме', 'Гостиная'),
    '卧室': ('Жатын бөлме', 'Спальня'),
    '厨房': ('Ас үй', 'Кухня'),
    '卫生间': ('Жуыну бөлмесі', 'Санузел'),
    '餐厅': ('Асхана', 'Столовая'),
    '门厅': ('Кіреберіс', 'Прихожая'),
    '走廊': ('Дәліз', 'Коридор'),
    '储藏间': ('Қойма', 'Кладовая'),
    '锅炉房': ('Қазандық', 'Котельная'),
    '房间': ('Бөлме', 'Комната'),
  };
  final room = rooms[zh];
  if (room != null) {
    return switch (appLang) {
      AppLang.en => enText(room.$1) ?? room.$2,
      AppLang.ky => kyText(room.$1) ?? room.$2,
      AppLang.uz => uzText(room.$1) ?? room.$2,
      AppLang.ru => room.$2,
      _ => room.$1,
    };
  }
  const numerals = '一二三四五六七八九十';
  final floor = RegExp(r'^([一二三四五六七八九十])楼$').firstMatch(zh);
  if (floor != null) {
    final n = numerals.indexOf(floor[1]!) + 1;
    return switch (appLang) {
      AppLang.en => 'floor $n',
      AppLang.ru => '$n-й этаж',
      AppLang.ky => '$n-кабат',
      AppLang.uz => '$n-qavat',
      _ => '$n-қабат',
    };
  }
  return zh;
}

/// Two objects claim the same cells. The core names them by id, which
/// means nothing to the person drawing.
final _overlap = RegExp(r'^对象 \S+ 与 \S+ 占用重叠$');

String coreMessage(String zh) {
  if (_overlap.hasMatch(zh)) {
    return tr3('这里已经被占用了，换个位置试试。', 'Бұл жер бос емес, басқа орынды таңдаңыз.',
        'Это место уже занято, выберите другое.',
        'This spot is taken; pick another.', ky: 'Бул орун ээленген; башкасын тандаңыз.', uz: 'Bu joy band; boshqasini tanlang.');
  }
  if (!isWestern) return zh;
  final exact = _exact[zh];
  if (exact != null) return tr(zh, exact);
  for (final (re, kk, ru, en, ky, uz) in _patterns) {
    final m = re.firstMatch(zh);
    if (m != null) {
      return switch (appLang) {
        AppLang.en => en(m),
        AppLang.ru => ru(m),
        AppLang.ky => ky(m),
        AppLang.uz => uz(m),
        _ => kk(m),
      };
    }
  }
  return zh;
}
