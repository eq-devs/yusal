#!/usr/bin/env python3
"""Regenerates lib/features/shared/brand/brand_data.dart from the logo SVGs.

Sources (tool/brand/svg, exported from the Yusal "puzzle house" logo book):
  mark.svg            the three-piece mark, gap 1g
  mark-small.svg      the small-size mark, gap 1.6g (for heights under 32)
  lockup-h-light.svg  mark + "Yusal" wordmark (wordmark path carries a
                      translate/scale transform)

Each SVG <path> becomes a flat op list read by pathFromOps():
  0 x y = moveTo, 1 x y = lineTo, 2 x1 y1 x2 y2 x y = cubicTo, 3 = close.

Run from the repo root:  python3 tool/brand/gen_brand.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'lib', 'features', 'shared', 'brand',
                   'brand_data.dart')
PIECES = ['top', 'left', 'right']  # roof (orange), left wall, right wall


def read(name):
    return open(os.path.join(HERE, 'svg', name)).read()


def ops(d, tx=0.0, ty=0.0, s=1.0):
    """Absolute M/L/H/V/C/Z path data -> op list, with an optional
    translate(tx, ty) scale(s) applied."""
    toks = re.findall(r'[MLHVCZ]|-?\d*\.?\d+(?:e-?\d+)?', d)
    out, i, cmd = [], 0, None
    x = y = 0.0
    P = lambda px, py: [round(tx + px * s, 2), round(ty + py * s, 2)]
    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            cmd = t
            i += 1
            if cmd == 'Z':
                out.append(3)
            continue
        n = lambda k: float(toks[i + k])
        if cmd in 'ML':
            x, y = n(0), n(1)
            out += [0 if cmd == 'M' else 1] + P(x, y)
            i += 2
            if cmd == 'M':
                cmd = 'L'
        elif cmd == 'H':
            x = n(0)
            out += [1] + P(x, y)
            i += 1
        elif cmd == 'V':
            y = n(0)
            out += [1] + P(x, y)
            i += 1
        elif cmd == 'C':
            out += [2] + P(n(0), n(1)) + P(n(2), n(3)) + P(n(4), n(5))
            x, y = n(4), n(5)
            i += 6
        else:
            raise ValueError(f'unsupported path command {cmd}')
    return out


def paths(svg):
    return re.findall(r'<path((?: transform="[^"]*")?) d="([^"]*)"', svg)


def mark_parts(svg):
    return [(PIECES[k], ops(d)) for k, (_, d) in enumerate(paths(svg)[:3])]


def word_part(svg):
    tf, d = paths(svg)[3]
    tx, ty, s = map(float, re.findall(
        r'translate\(([-\d.]+),([-\d.]+)\) scale\(([-\d.]+)\)', tf)[0])
    return ('word', ops(d, tx, ty, s))


def view(svg):
    w, h = re.search(r'viewBox="0 0 ([\d.]+) ([\d.]+)"', svg).groups()
    return float(w), float(h)


def fmt(v):
    return str(int(v)) if v == int(v) else repr(v)


def const(name, size, parts):
    """Small cuts share their full-size twin's box, so get no size."""
    body = ',\n'.join(
        f'  (_Piece.{p}, [{", ".join(fmt(v) for v in o)}])' for p, o in parts)
    head = '' if size is None else (
        f'const Size {name}Size = Size({fmt(size[0])}, {fmt(size[1])});\n')
    return (head + f'const List<(_Piece, List<double>)> {name} = [\n{body},\n];\n')


mark, small, lockup = read('mark.svg'), read('mark-small.svg'), read(
    'lockup-h-light.svg')
word = word_part(lockup)
src = ('// GENERATED by tool/brand/gen_brand.py from tool/brand/svg.\n'
       '// Do not edit by hand: regenerate from the SVG sources instead.\n'
       '// dart format off\n'
       "part of 'brand.dart';\n\n"
       + const('_mark', view(mark), mark_parts(mark)) + '\n'
       + const('_markSmall', None, mark_parts(small)) + '\n'
       + const('_lockup', view(lockup), mark_parts(lockup) + [word]) + '\n'
       + const('_lockupSmall', None, mark_parts(small) + [word]))
open(OUT, 'w').write(src)
print('wrote', os.path.relpath(OUT), len(src), 'bytes')
