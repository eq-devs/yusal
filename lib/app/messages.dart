String _d(String number) => number.replaceAll('.', ',');

/// Default room and floor names inside core messages, in Kazakh.
String _name(String zh) {
  const rooms = {
    '客厅': 'Қонақ бөлме',
    '卧室': 'Жатын бөлме',
    '厨房': 'Ас үй',
    '卫生间': 'Жуыну бөлмесі',
    '餐厅': 'Асхана',
    '房间': 'Бөлме',
  };
  final room = rooms[zh];
  if (room != null) return room;
  const numerals = '一二三四五六七八九十';
  final floor = RegExp(r'^([一二三四五六七八九十])楼$').firstMatch(zh);
  if (floor != null) return '${numerals.indexOf(floor[1]!) + 1}-қабат';
  return zh;
}

String coreMessage(String zh) {
  if (!isKk) return zh;
  final exact = _exact[zh];
  if (exact != null) return exact;
  for (final (re, build) in _patterns) {
    final m = re.firstMatch(zh);
    if (m != null) return build(m);
  }
  return zh;
}
