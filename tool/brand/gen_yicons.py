#!/usr/bin/env python3
"""Builds the Yusal icon font and its Dart bindings from tool/brand/icons.json
(the logo book's icon set: 24 grid, 2u round strokes, one orange piece).

Writes
  assets/fonts/YusalIcons.ttf            one font, three glyphs per icon
  lib/features/shared/brand/yicons.dart  YIcons (IconData) and YIcon (enum)

Each icon has its whole drawing as one glyph (YIcons.x, a drop-in for
Icons.x), and its ink part and its orange piece as two more glyphs, which
YusalIcon stacks to draw the icon in two colours.

Code points are taken from the order of icons.json: append new icons at the
end so the existing ones keep theirs.

Needs fonttools and skia-pathops.  Run from the repo root:
    python3 tool/brand/gen_yicons.py
"""
import json
import os

import pathops
from fontTools.fontBuilder import FontBuilder
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
FONT = os.path.join(ROOT, 'assets', 'fonts', 'YusalIcons.ttf')
DART = os.path.join(ROOT, 'lib', 'features', 'shared', 'brand', 'yicons.dart')

SPEC = json.load(open(os.path.join(HERE, 'icons.json')))
GRID, STROKE = SPEC['grid'], SPEC['stroke']
K = 40  # font units per grid unit
EM = GRID * K
FULL, INK, ACCENT = 0xE000, 0xE400, 0xE800


def outline(shapes):
    """The union of the shapes, strokes widened into outlines."""
    parts = []
    for s in shapes:
        p = pathops.Path()
        parse_path(s['d'], p.getPen())
        if s['role'] in 'sa':
            p.stroke(STROKE, pathops.LineCap.ROUND_CAP,
                     pathops.LineJoin.ROUND_JOIN, 4)
        p.convertConicsToQuads()
        parts.append(p)
    out = parts[0]
    for p in parts[1:]:
        out = pathops.op(out, p, pathops.PathOp.UNION)
    out.simplify()
    out.convertConicsToQuads()
    return out


def glyph(path):
    pen = TTGlyphPen(None)
    # Grid units, y down -> font units, y up.
    path.draw(Cu2QuPen(TransformPen(pen, (K, 0, 0, -K, 0, EM)), 0.4,
                       reverse_direction=True))
    return pen.glyph()


def dart_name(name):
    head, *rest = name.split('-')
    n = head + ''.join(w.capitalize() for w in rest)
    return {'external': 'openExternal'}.get(n, n)


glyphs = {'.notdef': TTGlyphPen(None).glyph()}
cmap = {}
rows = []
for i, (name, icon) in enumerate(SPEC['icons'].items()):
    shapes = icon['shapes']
    ink = [s for s in shapes if s['role'] in 'sF']
    acc = [s for s in shapes if s['role'] in 'aA']
    layers = {}
    for base, tag, part in ((FULL, 'full', shapes), (INK, 'ink', ink),
                            (ACCENT, 'accent', acc)):
        if not part or (tag != 'full' and not acc):
            continue
        g = f'{name}.{tag}'
        glyphs[g] = glyph(outline(part))
        cmap[base + i] = g
        layers[tag] = base + i
    rows.append((dart_name(name), icon['label'], layers))

fb = FontBuilder(EM, isTTF=True)
fb.setupGlyphOrder(list(glyphs))
fb.setupCharacterMap(cmap)
fb.setupGlyf(glyphs)
# The left side bearing has to be the outline's own xMin, or renderers
# slide every glyph to the left edge of its box.
fb.setupHorizontalMetrics(
    {g: (EM, getattr(fb.font['glyf'][g], 'xMin', 0)) for g in glyphs})
fb.setupHorizontalHeader(ascent=EM, descent=0, lineGap=0)
fb.setupNameTable({'familyName': 'YusalIcons', 'styleName': 'Regular'})
fb.setupOS2(sTypoAscender=EM, sTypoDescender=0, sTypoLineGap=0,
            usWinAscent=EM, usWinDescent=0)
fb.setupPost()
os.makedirs(os.path.dirname(FONT), exist_ok=True)
fb.save(FONT)

hx = lambda v: f'0x{v:04x}'
src = [
    '// GENERATED by tool/brand/gen_yicons.py from tool/brand/icons.json.',
    '// Do not edit by hand: regenerate instead.',
    '// dart format off',
    "import 'package:flutter/widgets.dart';",
    '',
    "const String _f = 'YusalIcons';",
    '',
    '/// The Yusal icons as [IconData], in one colour: use them wherever an',
    '/// `Icons.x` would go. [YusalIcon] draws the same icons with their one',
    '/// orange piece.',
    'abstract final class YIcons {',
]
for n, label, layers in rows:
    src += [f'  /// {label}',
            f'  static const IconData {n} = IconData({hx(layers["full"])}, fontFamily: _f);']
src += ['}', '',
        '/// The Yusal icons with their layers, for [YusalIcon].',
        'enum YIcon {']
for n, label, layers in rows:
    ink = f'IconData({hx(layers["ink"])}, fontFamily: _f)' if 'ink' in layers else 'null'
    acc = f'IconData({hx(layers["accent"])}, fontFamily: _f)' if 'accent' in layers else 'null'
    src += [f'  /// {label}', f'  {n}(YIcons.{n}, {ink}, {acc}),']
src += ['  ;', '',
        '  const YIcon(this.glyph, this.ink, this.accent);', '',
        '  /// The whole icon as one glyph.',
        '  final IconData glyph;', '',
        '  /// The ink part alone; null when the icon has no orange piece.',
        '  final IconData? ink;', '',
        '  /// The orange piece alone; null when the icon has none.',
        '  final IconData? accent;',
        '}', '']
open(DART, 'w').write('\n'.join(src))
print(f'{len(rows)} icons, {len(glyphs) - 1} glyphs -> '
      f'{os.path.relpath(FONT, ROOT)} ({os.path.getsize(FONT)} bytes)')
